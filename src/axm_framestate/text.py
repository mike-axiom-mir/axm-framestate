BOX=["11111","10001","10101","10101","10101","10001","11111"]


def glyph(ch: str) -> list[str]:
    return FONT.get(ch.upper(), BOX)


def measure(text: str, scale: int) -> tuple[int, int]:
    lines = text.split("\n") or [""]
    width = max((len(line) * 6 - 1 for line in lines), default=0) * scale
    height = len(lines) * 8 * scale - scale
    return max(0, width), max(0, height)


def raster(text: str, scale: int, color: list[int]) -> tuple[int, int, list[tuple[int,int,int] | None]]:
    w, h = measure(text, scale)
    out: list[tuple[int,int,int] | None] = [None] * max(0, w*h)
    if w == 0 or h == 0:
        return w, h, out
    rgb = tuple(color)
    for line_i, line in enumerate(text.split("\n")):
        for char_i, ch in enumerate(line):
            pattern = glyph(ch)
            ox = char_i * 6 * scale
            oy = line_i * 8 * scale
            for gy, row in enumerate(pattern):
                for gx, bit in enumerate(row):
                    if bit != "1": continue
                    for yy in range(scale):
                        py = oy + gy * scale + yy
                        for xx in range(scale):
                            px = ox + gx * scale + xx
                            if 0 <= px < w and 0 <= py < h:
                                out[py*w+px] = rgb
    return w, h, out
